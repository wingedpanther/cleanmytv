    fun getScanCode(name: String): Int? {
        SCAN_CODES[name]?.let { return it }
        val upper = name.uppercase()
        SCAN_CODES[upper]?.let { return it }
        if (!upper.startsWith("KEY_") && !upper.startsWith("BTN_")) {
            SCAN_CODES["KEY_$upper"]?.let { return it }
            SCAN_CODES["BTN_$upper"]?.let { return it }
        }
        return null
    }
